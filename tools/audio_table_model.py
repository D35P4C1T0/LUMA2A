#!/usr/bin/env python3
"""Generate bounded, smooth statistical variations and verify reference audio.

Uses only the Python standard library. The proprietary binary and audio corpus
are local validation inputs and are never embedded in the generated report.
"""
import argparse
import array
import hashlib
import json
import math
import pathlib
import random
import re
import struct
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
REFERENCE_SHA256 = "f9d1852e3cf54ee9364a645f8c01e4aca3bcf33d41ade7ecfad50183cb0e2b32"
OFFSETS = (0x176E08, 0x17AE18, 0x17EE28, 0x182E38)
SEED = 0x554241
LIMIT = 0.005
CENTRE_POWER = 2


def reference_tables(path):
    binary = path.read_bytes()
    if hashlib.sha256(binary).hexdigest() != REFERENCE_SHA256:
        raise ValueError("Reference binary SHA-256 mismatch")
    return [struct.unpack_from("<2048d", binary, offset) for offset in OFFSETS]


def model(tables):
    # A finite Gaussian cosine series is a smooth random field. Fixed seed and
    # explicit coefficients make the realization reproducible across runs.
    rng = random.Random(SEED)
    result, coefficients = [], []
    for reference in tables:
        weights = [rng.gauss(0, 1) / (k + 1)**2 for k in range(6)]
        coefficients.append(weights)
        field = []
        for i in range(2048):
            x = i / 2047
            field.append(sum(w * math.cos(k * math.pi * x)
                             for k, w in enumerate(weights)) * abs(2*x - 1)**CENTRE_POWER)
        peak = max(map(abs, field))
        # nextafter gives room for binary64 rounding at the 0.5% boundary.
        amplitude = math.nextafter(LIMIT, 0)
        varied = []
        for value, deviation in zip(reference, field):
            candidate = value * (1 + amplitude * deviation / peak)
            while abs(candidate - value) > LIMIT * abs(value):
                candidate = math.nextafter(candidate, value)
            varied.append(candidate)
        result.append(varied)
    return result, coefficients


def header(tables):
    text = ('#pragma once\n#include <array>\n'
            '// Generated by tools/audio_table_model.py; see docs/audio-table-model.md.\n'
            'namespace audioTables {\n')
    for stage, values in enumerate(tables, 1):
        text += f'inline constexpr std::array<double,2048> stage{stage} = {{\n'
        text += ''.join(value.hex() + ',\n' for value in values) + '};\n'
    return text + '}\n'


def installed_tables():
    source = (ROOT / 'Source/AudioTables.h').read_text()
    bodies = re.findall(r'stage\d = \{(.*?)\};', source, re.S)
    values = [[float.fromhex(s.strip()) for s in body.split(',') if s.strip()]
              for body in bodies]
    if len(values) != 4 or any(len(v) != 2048 for v in values):
        raise ValueError('Expected four 2048-entry audio tables')
    return values


def read_audio(path):
    values = array.array('f')
    values.frombytes(path.read_bytes())
    if sys.byteorder != 'little':
        values.byteswap()
    return values


def audio_checks(renderer, corpus, manifest):
    cases = json.loads(manifest.read_text())
    results, skipped = [], []
    with tempfile.TemporaryDirectory(prefix='luma-table-check-') as temp:
        output = pathlib.Path(temp) / 'output.f32'
        for case in cases:
            # Offline renderer supports static DSP controls; host bypass and
            # event delivery require a plugin host and are explicitly excluded.
            if ('input' not in case or case.get('events') or
                    any(int(k) < 2 for k in case.get('parameters', {}))):
                skipped.append(pathlib.PureWindowsPath(case['output']).stem)
                continue
            win = pathlib.PureWindowsPath(case['input'])
            source = corpus / win.parent.name / win.name
            if not source.exists():
                source = corpus / 'windows' / win.name
            reference = source.with_name(source.name.replace('.input.f32', '.reference.f32'))
            if not source.exists() or not reference.exists():
                raise ValueError(f'Missing corpus pair: {source}')
            parameters = [1, 1, 0, .75, 0, .24, 0, .25, 1, .5]
            for key, value in case.get('parameters', {}).items():
                parameters[int(key) - 2] = value
            subprocess.run([str(renderer), str(source), str(output), str(case['rate']),
                            str(case['channels']), str(case['block']),
                            'double' if case.get('double') else 'float',
                            *map(str, parameters)], check=True)
            a, b = read_audio(reference), read_audio(output)
            if len(a) != len(b) or len(a) != case['samples'] * case['channels']:
                raise ValueError(f'Audio length mismatch: {source.name}')
            if not all(math.isfinite(v) for values in (a, b) for v in values):
                raise ValueError(f'Nonfinite reference or output: {source.name}')
            peak = max(map(abs, a))
            energy = sum(v*v for v in a)
            errors = [float(y) - float(x) for x, y in zip(a, b)]
            absolute = max(map(abs, errors))
            peak_error = absolute / peak if peak else (0 if absolute == 0 else math.inf)
            error_energy = sum(v*v for v in errors)
            rms_error = math.sqrt(error_energy / energy) if energy else peak_error
            results.append(dict(name=source.stem, rate=case['rate'],
                                channels=case['channels'], samples=len(a),
                                input_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                                reference_audio_sha256=hashlib.sha256(reference.read_bytes()).hexdigest(),
                                max_absolute_error=absolute,
                                peak_normalized_error=peak_error,
                                relative_rms_error=rms_error))
    if not results:
        raise ValueError('No reference audio cases were checked')
    return dict(cases=results, skipped_cases=skipped, total_cases=len(results),
                total_samples=sum(c['samples'] for c in results),
                max_peak_normalized_error=max(c['peak_normalized_error'] for c in results),
                max_relative_rms_error=max(c['relative_rms_error'] for c in results))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', type=pathlib.Path, required=True)
    parser.add_argument('--write', action='store_true', help='Regenerate AudioTables.h')
    parser.add_argument('--renderer', type=pathlib.Path)
    parser.add_argument('--corpus', type=pathlib.Path, default=ROOT / 'evidence')
    parser.add_argument('--report', type=pathlib.Path)
    args = parser.parse_args()
    reference = reference_tables(args.reference)
    generated, coefficients = model(reference)
    if args.write:
        (ROOT / 'Source/AudioTables.h').write_text(header(generated))
    actual = installed_tables()
    if actual != generated:
        raise ValueError('Installed tables do not match the seeded statistical model')
    report = dict(reference_sha256=REFERENCE_SHA256, seed=SEED, limit=LIMIT,
                  centre_power=CENTRE_POWER, gaussian_cosine_coefficients=coefficients,
                  audio_tables_sha256=hashlib.sha256((ROOT / 'Source/AudioTables.h').read_bytes()).hexdigest(),
                  tables=[])
    for i, (old, new) in enumerate(zip(reference, actual), 1):
        errors = [abs(b-a)/abs(a) if a else abs(b) for a, b in zip(old, new)]
        if max(errors) > LIMIT:
            raise ValueError(f'Stage {i} exceeds the pointwise table bound')
        report['tables'].append(dict(stage=i, entries=len(old),
                                     changed_entries=sum(a != b for a, b in zip(old, new)),
                                     max_relative_error=max(errors),
                                     rms_relative_error=math.sqrt(sum(e*e for e in errors)/len(errors))))
    if args.renderer:
        report['audio'] = audio_checks(args.renderer.resolve(), args.corpus,
                                      args.corpus / 'final-vector/manifest.json')
    if args.report:
        args.report.write_text(json.dumps(report, indent=2, allow_nan=False) + '\n')
    print(json.dumps({k: v for k, v in report.items()
                      if k not in ('audio', 'gaussian_cosine_coefficients')}, indent=2))
    if args.renderer:
        print(json.dumps({k: v for k, v in report['audio'].items()
                          if k not in ('cases', 'skipped_cases')}, indent=2))
        if max(report['audio']['max_peak_normalized_error'],
               report['audio']['max_relative_rms_error']) > LIMIT:
            raise ValueError('Rendered audio exceeds the 0.5% error bound')


if __name__ == '__main__':
    main()
